/* Writes a C file of Lua sources for Boot. The bytes are hex so the
 * mark's box-drawing characters need no extra escaping.
 */

#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void die(const char *text)
{
    fprintf(stderr, "lua-embed: %s\n", text);
    exit(1);
}

static unsigned char *read_all(const char *path, size_t *length)
{
    FILE *fp;
    unsigned char *buf;
    long size;
    size_t n;

    fp = fopen(path, "rb");
    if (fp == 0)
        die(path);
    if (fseek(fp, 0, SEEK_END) != 0)
        die(path);
    size = ftell(fp);
    if (size < 0)
        die(path);
    if (fseek(fp, 0, SEEK_SET) != 0)
        die(path);
    buf = malloc((size_t)size + 1u);
    if (buf == 0)
        die("out of memory");
    n = fread(buf, 1, (size_t)size, fp);
    fclose(fp);
    if (n != (size_t)size)
        die(path);
    *length = n;
    return buf;
}

static void write_bytes(FILE *out, const char *symbol, const unsigned char *buf,
                        size_t length)
{
    size_t i;

    fprintf(out, "static const unsigned char %s[] = {\n", symbol);
    for (i = 0; i < length; i++) {
        if (i % 16u == 0)
            fputs("    ", out);
        fprintf(out, "0x%02x", buf[i]);
        if (i + 1 < length)
            fputc(',', out);
        if (i % 16u == 15u || i + 1 == length)
            fputc('\n', out);
        else
            fputc(' ', out);
    }
    fputs("};\n", out);
}

int main(int argc, char **argv)
{
    FILE *out;
    int i;
    int count;

    if (argc < 4 || ((argc - 2) % 2) != 0)
        die("usage: lua-embed OUT name path ...");
    out = fopen(argv[1], "w");
    if (out == 0)
        die(argv[1]);
    fputs("/* Generated by tools/lua-embed. Do not edit. */\n", out);
    fputs("#include \"guest-scripts.h\"\n\n", out);
    fputs("#include <string.h>\n\n", out);
    count = (argc - 2) / 2;
    for (i = 0; i < count; i++) {
        const char *name = argv[2 + i * 2];
        const char *path = argv[3 + i * 2];
        size_t length = 0;
        unsigned char *buf = read_all(path, &length);
        char symbol[128];

        if (strlen(name) > 60)
            die("name is too long");
        snprintf(symbol, sizeof symbol, "script_%d", i);
        write_bytes(out, symbol, buf, length);
        free(buf);
        (void)name;
    }
    fputs("\nstatic const QueueosLuaScript scripts[] = {\n", out);
    for (i = 0; i < count; i++) {
        const char *name = argv[2 + i * 2];
        fprintf(out, "    { \"%s\", script_%d, (unsigned)sizeof script_%d },\n",
                name, i, i);
    }
    fputs("};\n\n", out);
    fputs("const QueueosLuaScript *queueos_lua_script(const char *name)\n", out);
    fputs("{\n    unsigned i;\n\n    if (name == 0)\n        return 0;\n", out);
    fputs("    for (i = 0; i < (unsigned)(sizeof scripts / sizeof scripts[0]); i++) {\n", out);
    fputs("        if (strcmp(scripts[i].name, name) == 0)\n", out);
    fputs("            return &scripts[i];\n    }\n    return 0;\n}\n", out);
    if (fclose(out) != 0)
        die(argv[1]);
    return 0;
}
